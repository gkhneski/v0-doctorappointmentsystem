-- 8. adımın geri alınması: kuralları adımdan önceki hâline döndürür.
begin;
create policy "Admin can view documents" on public.patient_documents for select to authenticated using (true);
create policy "Admin can insert documents" on public.patient_documents for insert to authenticated with check (true);
create policy "Admin can update documents" on public.patient_documents for update to authenticated using (true) with check (true);
create policy "Admin can delete documents" on public.patient_documents for delete to authenticated using (true);
drop policy "patient_documents_staff_all" on public.patient_documents;
create policy "Admin can view templates" on public.message_templates for select to authenticated using (true);
create policy "Admin can insert templates" on public.message_templates for insert to authenticated with check (true);
create policy "Admin can update templates" on public.message_templates for update to authenticated using (true);
create policy "Admin can delete templates" on public.message_templates for delete to authenticated using (true);
drop policy "message_templates_staff_all" on public.message_templates;
create policy "Admin can view sent messages" on public.sent_messages for select to authenticated using (true);
create policy "Admin can insert sent messages" on public.sent_messages for insert to authenticated with check (true);
drop policy "sent_messages_staff_select" on public.sent_messages;
drop policy "sent_messages_staff_insert" on public.sent_messages;
create policy "System can create sms verifications" on public.sms_verifications for insert to authenticated with check (true);
create policy "System can update sms verifications" on public.sms_verifications for update to authenticated using (true);
drop policy "sms_verifications_staff_insert" on public.sms_verifications;
drop policy "sms_verifications_staff_update" on public.sms_verifications;
create policy "Admin can view references" on public."references" for select using (true);
create policy "Admin can insert references" on public."references" for insert with check (true);
drop policy "references_staff_select" on public."references";
drop policy "references_staff_insert" on public."references";
create policy "Authenticated users can view documents" on storage.objects for select to authenticated using (bucket_id = 'patient-documents');
create policy "Authenticated users can upload documents" on storage.objects for insert to authenticated with check (bucket_id = 'patient-documents');
create policy "Authenticated users can delete documents" on storage.objects for delete to authenticated using (bucket_id = 'patient-documents');
create policy "Authenticated users can upload patient photos" on storage.objects for insert to authenticated with check (bucket_id = 'patient-photos');
create policy "Authenticated users can delete patient photos" on storage.objects for delete to authenticated using (bucket_id = 'patient-photos');
drop policy "staff_storage_select" on storage.objects;
drop policy "staff_storage_insert" on storage.objects;
drop policy "staff_storage_delete" on storage.objects;
commit;
