function fold(text: string): string {
  return text.toLocaleLowerCase("tr")
}

/** Arama: yazılan her kelime soruda ya da yanıtta geçmelidir. Boş aramada konunun bütün soruları döner. */
export function searchQuestions(query: string, category: QuestionCategory | "hepsi"): BankQuestion[] {
  const words = fold(query).split(/\s+/).filter((word) => word.length > 1)
  return QUESTIONS.filter((item) => {
    if (category !== "hepsi" && item.category !== category) return false
    const text = fold(`${item.question} ${item.answer}`)
    return words.every((word) => text.includes(word))
  })
}
