const NAME_SET = new Set(NAMES.map((n) => n.name))

/** Beğeni olarak yalnızca listedeki isimler kabul edilir. */
export function isKnownName(value: unknown): value is string {
  return typeof value === "string" && NAME_SET.has(value)
}

export type NameFilter = "kiz" | "erkek" | "hepsi"

/** Çarkta dönecek isimler: seçilen cinsiyetin isimleri ve iki cinsiyete de verilenler. */
export function namesFor(filter: NameFilter): BabyName[] {
  return filter === "hepsi" ? [...NAMES] : NAMES.filter((n) => n.kind === filter || n.kind === "ortak")
}

/** Bebeğin bilinen cinsiyetine göre çarkın açılış seçimi. */
export function filterForGender(gender: unknown): NameFilter {
  if (gender === "female") return "kiz"
  if (gender === "male") return "erkek"
  return "hepsi"
}
